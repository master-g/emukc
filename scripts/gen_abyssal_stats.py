#!/usr/bin/env python3
"""Regenerate the abyssal stats asset from the pinned source simulator.

Reads `js/kcSHIPDATA.js` of KC3Kai/kancolle-replay at COMMIT (downloaded, or the file given as
the first argument) and writes crates/emukc_bootstrap/assets/abyssal_stats.json: the `ASW`,
`EV`, `LOS` and `LUK` of every abyssal ship that has any, estimated figures (`unknownstats`)
included. Bootstrap takes them over kcwiki's enemy data, which has none for most of them. It
prints the counts and sums that the test `the_abyssal_stats_asset_follows_the_source` asserts;
rebuild the codex afterwards (`cargo run -- bootstrap --codex-only`).

    python3 scripts/gen_abyssal_stats.py [kcSHIPDATA.js]
"""

import json
import re
import sys
import urllib.request
from pathlib import Path

COMMIT = "69097abc"
URL = f"https://raw.githubusercontent.com/KC3Kai/kancolle-replay/{COMMIT}/js/kcSHIPDATA.js"
OUT = Path(__file__).resolve().parent.parent / "crates/emukc_bootstrap/assets/abyssal_stats.json"
# The source's abyssal ships (`isPlayable` is below 1500; 1501 to 3000 are abyssal).
ABYSSAL_IDS = range(1501, 3001)
# The source's field for each stat of the asset.
STATS = {"asw": "ASW", "evasion": "EV", "los": "LOS", "luck": "LUK"}


def parse(text: str) -> dict[str, dict[int, int]]:
    stats, ship = {stat: {} for stat in STATS}, None
    fields = {field: stat for stat, field in STATS.items()}
    for line in text.splitlines():
        if entry := re.match(r"\t(\d+): \{", line):
            ship = int(entry[1])
        elif ship in ABYSSAL_IDS and (field := re.match(r"\t\t(\w+): (\d+),", line)):
            if stat := fields.get(field[1]):
                stats[stat][ship] = int(field[2])
    return {stat: {ship: value for ship, value in values.items() if value}
            for stat, values in stats.items()}


def main() -> None:
    if len(sys.argv) > 1:
        text = Path(sys.argv[1]).read_text(encoding="utf-8")
    else:
        with urllib.request.urlopen(URL) as response:
            text = response.read().decode("utf-8")
    stats = parse(text)
    asset = {
        "note": f"Generated by scripts/gen_abyssal_stats.py from js/kcSHIPDATA.js of "
        f"KC3Kai/kancolle-replay at {COMMIT}: the ASW, evasion, LOS and luck of every abyssal "
        "ship that has any. Regenerate it; do not edit it by hand.",
    }
    for stat, values in stats.items():
        asset[stat] = {str(ship): value for ship, value in sorted(values.items())}
        print(f"{stat} above zero: {len(values)} ships, ids sum {sum(values)}, "
              f"sum {sum(values.values())}")
    OUT.write_text(json.dumps(asset, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
