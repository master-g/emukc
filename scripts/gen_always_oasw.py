#!/usr/bin/env python3
"""Regenerate the opening-ASW tables from the pinned source simulator.

Reads `js/kcSHIPDATA.js` of KC3Kai/kancolle-replay at COMMIT (downloaded, or the file given as
the first argument) and writes crates/emukc_battle/src/simulation/always_oasw.rs: the player's
ships and the abyssal ships marked `alwaysOASW`. It prints the counts and sums that the test
`the_always_oasw_tables_follow_the_source` asserts.

    python3 scripts/gen_always_oasw.py [kcSHIPDATA.js]
"""

import re
import subprocess
import sys
import urllib.request
from pathlib import Path

COMMIT = "69097abc"
URL = f"https://raw.githubusercontent.com/KC3Kai/kancolle-replay/{COMMIT}/js/kcSHIPDATA.js"
OUT = Path(__file__).resolve().parent.parent / "crates/emukc_battle/src/simulation/always_oasw.rs"
# The player's ships (`isPlayable`) and the abyssal ones; the source's entries from 3001 are its own
# (Vita) and not the game's.
PLAYER = range(1, 1500)
ABYSSAL = range(1501, 3001)


def parse(text: str) -> list[int]:
    found, ship = [], None
    for line in text.splitlines():
        if entry := re.match(r"\t(\d+): \{", line):
            ship = int(entry[1])
        elif ship is not None and re.match(r"\t\talwaysOASW: true,", line):
            found.append(ship)
    return sorted(found)


def main() -> None:
    if len(sys.argv) > 1:
        text = Path(sys.argv[1]).read_text(encoding="utf-8")
    else:
        with urllib.request.urlopen(URL) as response:
            text = response.read().decode("utf-8")
    marked = parse(text)
    players = [ship for ship in marked if ship in PLAYER]
    abyssal = [ship for ship in marked if ship in ABYSSAL]
    rows = lambda ships: "".join(f"    {ship},\n" for ship in ships)
    OUT.write_text(
        "//! Generated by `scripts/gen_always_oasw.py` from `kcSHIPDATA.js` of\n"
        f"//! `KC3Kai/kancolle-replay` at `{COMMIT}`. Regenerate it; do not edit it by hand.\n\n"
        "/// The player's ships the source marks `alwaysOASW`; it lets every one with 50 anti-submarine\n"
        "/// at level 1 open with ASW too.\n"
        f"pub(crate) const PLAYER_ALWAYS_OASW_IDS: &[i64] = &[\n{rows(players)}];\n\n"
        "/// The abyssal ships that open with ASW (`alwaysOASW`): the general rule's 100 anti-submarine\n"
        "/// with a sonar is for the player's ships only (`isPlayable`).\n"
        f"pub(crate) const ABYSSAL_ALWAYS_OASW_IDS: &[i64] = &[\n{rows(abyssal)}];\n",
        encoding="utf-8",
    )
    subprocess.run(["rustfmt", "--edition", "2024", str(OUT)], check=True)
    print(f"player alwaysOASW: {len(players)} ships, ids sum {sum(players)}")
    print(f"abyssal alwaysOASW: {len(abyssal)} ships, ids sum {sum(abyssal)}")


if __name__ == "__main__":
    main()
