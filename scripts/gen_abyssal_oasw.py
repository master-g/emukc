#!/usr/bin/env python3
"""Regenerate the abyssal opening-ASW table from the pinned source simulator.

Reads `js/kcSHIPDATA.js` of KC3Kai/kancolle-replay at COMMIT (downloaded, or the file given as
the first argument) and writes crates/emukc_battle/src/simulation/abyssal_oasw.rs: every
abyssal ship marked `alwaysOASW`, the only ones the source lets open with ASW by the general
rule. It prints the count and sum that the test `the_abyssal_oasw_table_follows_the_source`
asserts.

    python3 scripts/gen_abyssal_oasw.py [kcSHIPDATA.js]
"""

import re
import subprocess
import sys
import urllib.request
from pathlib import Path

COMMIT = "69097abc"
URL = f"https://raw.githubusercontent.com/KC3Kai/kancolle-replay/{COMMIT}/js/kcSHIPDATA.js"
OUT = Path(__file__).resolve().parent.parent / "crates/emukc_battle/src/simulation/abyssal_oasw.rs"
# Abyssal ship ids start here; the source's entries from 3001 are its own (Vita) and not the game's.
ABYSSAL = range(1501, 3001)


def parse(text: str) -> list[int]:
    found, ship = [], None
    for line in text.splitlines():
        if entry := re.match(r"\t(\d+): \{", line):
            ship = int(entry[1])
        elif ship in ABYSSAL and re.match(r"\t\talwaysOASW: true,", line):
            found.append(ship)
    return sorted(found)


def main() -> None:
    if len(sys.argv) > 1:
        text = Path(sys.argv[1]).read_text(encoding="utf-8")
    else:
        with urllib.request.urlopen(URL) as response:
            text = response.read().decode("utf-8")
    ships = parse(text)
    ids = "".join(f"    {ship},\n" for ship in ships)
    OUT.write_text(
        "//! Generated by `scripts/gen_abyssal_oasw.py` from `kcSHIPDATA.js` of\n"
        f"//! `KC3Kai/kancolle-replay` at `{COMMIT}`. Regenerate it; do not edit it by hand.\n\n"
        "/// The abyssal ships that open with ASW (`alwaysOASW`): the general rule's 100 anti-submarine\n"
        "/// with a sonar is for the player's ships only (`isPlayable`).\n"
        f"pub(crate) const ABYSSAL_ALWAYS_OASW_IDS: &[i64] = &[\n{ids}];\n",
        encoding="utf-8",
    )
    subprocess.run(["rustfmt", "--edition", "2024", str(OUT)], check=True)
    print(f"alwaysOASW: {len(ships)} ships, ids sum {sum(ships)}")


if __name__ == "__main__":
    main()
