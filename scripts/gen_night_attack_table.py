#!/usr/bin/env python3
"""Regenerate the night attack type table from the pinned source simulator.

Reads `js/kcsim.js` and `js/kcEQDATA.js` of KC3Kai/kancolle-replay at COMMIT (downloaded, or
the two files given as arguments) and writes
crates/emukc_battle/src/simulation/night_attack_table.rs: the `NBATTACKDATA` rows of the double
attack, the four general cut-ins and the eight destroyer cut-ins, and the torpedoes marked
`specialCutIn`. It prints the rows as the tuples the test
`the_night_attack_table_follows_the_source` asserts.

    python3 scripts/gen_night_attack_table.py [kcsim.js kcEQDATA.js]
"""

import re
import subprocess
import sys
import urllib.request
from pathlib import Path

COMMIT = "69097abc"
URL = f"https://raw.githubusercontent.com/KC3Kai/kancolle-replay/{COMMIT}/js/"
OUT = Path(__file__).resolve().parent.parent / "crates/emukc_battle/src/simulation/night_attack_table.rs"
# The carrier cut-ins (61-64) and the night Zuiun cut-ins (2001-2004) are not in this table.
IDS = [1, 2, 3, 4, 5, 7, 8, 9, 10, 11, 12, 13, 14]


def read(name: str, index: int) -> str:
    if len(sys.argv) > 2:
        return Path(sys.argv[index]).read_text(encoding="utf-8")
    with urllib.request.urlopen(URL + name) as response:
        return response.read().decode("utf-8")


def number(body: str, key: str, default: str) -> str:
    found = re.search(rf"\b{key}: ([\d.]+)", body)
    value = found[1] if found else default
    return f"0{value}" if value.startswith(".") else value


def rows(sim: str) -> list[tuple]:
    table = sim[sim.index("var NBATTACKDATA = {") :]
    table = table[: table.index("\n}")]
    out = []
    for attack in IDS:
        body = re.search(rf"^\t{attack}: \{{(.*)\}},$", table, re.M)[1]
        replace = number(body, "replace", "0")
        out.append(
            (
                attack,
                number(body, "dmgMod", ""),
                number(body, "accMod", ""),
                number(body, "chanceMod", ""),
                number(body, "numHits", "1"),
                "true" if "torpedo: true" in body else "false",
                replace,
                number(body, "replaceChance", "0"),
            )
        )
    return out


def special_torpedoes(equipment: str) -> list[int]:
    ids, item = [], None
    for line in equipment.splitlines():
        if entry := re.match(r"\t(\d+): \{", line):
            item = int(entry[1])
        elif "specialCutIn: true" in line:
            ids.append(item)
    return ids


def floating(value: str) -> str:
    return value if "." in value else f"{value}.0"


def main() -> None:
    table = rows(read("kcsim.js", 1))
    torpedoes = special_torpedoes(read("kcEQDATA.js", 2))
    body = "".join(
        f"    NightAttackRow {{ id: {a}, damage: {floating(d)}, accuracy: {floating(c)}, "
        f"chance: {floating(m)}, hits: {h}, torpedo: {t}, replace: {r}, "
        f"replace_chance: {floating(p)} }},\n"
        for a, d, c, m, h, t, r, p in table
    )
    ids = "".join(f"    {item},\n" for item in torpedoes)
    OUT.write_text(
        "//! Generated by `scripts/gen_night_attack_table.py` from `kcsim.js` and `kcEQDATA.js` of\n"
        f"//! `KC3Kai/kancolle-replay` at `{COMMIT}`. Regenerate it; do not edit it by hand.\n\n"
        "/// One row of the source's `NBATTACKDATA`.\n"
        "pub(crate) struct NightAttackRow {\n"
        "    /// The attack type, as `api_sp_list` carries it.\n"
        "    pub(crate) id: i64,\n"
        "    /// `dmgMod`.\n"
        "    pub(crate) damage: f64,\n"
        "    /// `accMod`.\n"
        "    pub(crate) accuracy: f64,\n"
        "    /// `chanceMod`; 0 marks the double attack, which fires at 99%.\n"
        "    pub(crate) chance: f64,\n"
        "    /// `numHits`, 1 where the source leaves it out.\n"
        "    pub(crate) hits: usize,\n"
        "    /// `torpedo`: the attack is not made on an installation.\n"
        "    pub(crate) torpedo: bool,\n"
        "    /// `replace`: the two-hit attack a destroyer of level 80 may make instead, or 0.\n"
        "    pub(crate) replace: i64,\n"
        "    /// `replaceChance`.\n"
        "    pub(crate) replace_chance: f64,\n"
        "}\n\n"
        "/// The double attack (1), the general cut-ins (2-5) and the destroyer cut-ins (7-14).\n"
        f"#[rustfmt::skip]\npub(crate) const NIGHT_ATTACKS: &[NightAttackRow] = &[\n{body}];\n\n"
        "/// The torpedoes marked `specialCutIn` (後期型 and the like): they raise a submarine's\n"
        "/// torpedo cut-in.\n"
        f"pub(crate) const SPECIAL_TORPEDO_IDS: &[i64] = &[\n{ids}];\n",
        encoding="utf-8",
    )
    subprocess.run(["rustfmt", "--edition", "2024", str(OUT)], check=True)
    # (id, dmgMod, accMod, chanceMod, numHits, torpedo, replace, replaceChance)
    for a, d, c, m, h, t, r, p in table:
        print(f"({a}, {floating(d)}, {floating(c)}, {floating(m)}, {h}, {t}, {r}, {floating(p)}),")
    print(f"specialCutIn: {len(torpedoes)} torpedoes, ids sum {sum(torpedoes)}")


if __name__ == "__main__":
    main()
