#!/usr/bin/env python3
"""Regenerate the abyssal anti-submarine asset from the pinned source simulator.

Reads `js/kcSHIPDATA.js` of KC3Kai/kancolle-replay at COMMIT (downloaded, or the file given as
the first argument) and writes crates/emukc_bootstrap/assets/abyssal_asw.json: the `ASW` of
every abyssal ship that has any. Bootstrap takes it over kcwiki's enemy data, which has none
for most of them. It prints the count and sums that the test `the_abyssal_asw_asset_follows_the_source`
asserts; rebuild the codex afterwards (`cargo run -- bootstrap --codex-only`).

    python3 scripts/gen_abyssal_asw.py [kcSHIPDATA.js]
"""

import json
import re
import sys
import urllib.request
from pathlib import Path

COMMIT = "69097abc"
URL = f"https://raw.githubusercontent.com/KC3Kai/kancolle-replay/{COMMIT}/js/kcSHIPDATA.js"
OUT = Path(__file__).resolve().parent.parent / "crates/emukc_bootstrap/assets/abyssal_asw.json"
# The source's abyssal ships (`isPlayable` is below 1500; 1501 to 3000 are abyssal).
ABYSSAL = range(1501, 3001)


def parse(text: str) -> dict[int, int]:
    asw, ship = {}, None
    for line in text.splitlines():
        if entry := re.match(r"\t(\d+): \{", line):
            ship = int(entry[1])
        elif ship in ABYSSAL and (value := re.match(r"\t\tASW: (\d+),", line)):
            asw[ship] = int(value[1])
    return {ship: value for ship, value in asw.items() if value}


def main() -> None:
    if len(sys.argv) > 1:
        text = Path(sys.argv[1]).read_text(encoding="utf-8")
    else:
        with urllib.request.urlopen(URL) as response:
            text = response.read().decode("utf-8")
    asw = parse(text)
    asset = {
        "note": f"Generated by scripts/gen_abyssal_asw.py from js/kcSHIPDATA.js of "
        f"KC3Kai/kancolle-replay at {COMMIT}: the ASW of every abyssal ship that has any. "
        "Regenerate it; do not edit it by hand.",
        "asw": {str(ship): value for ship, value in sorted(asw.items())},
    }
    OUT.write_text(json.dumps(asset, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"ASW above zero: {len(asw)} ships, ids sum {sum(asw)}, ASW sum {sum(asw.values())}")


if __name__ == "__main__":
    main()
