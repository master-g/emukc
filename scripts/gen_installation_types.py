#!/usr/bin/env python3
"""Regenerate the abyssal land-target table from the pinned source simulator.

Reads `js/kcSHIPDATA.js` of KC3Kai/kancolle-replay at COMMIT (downloaded, or the file given as
the first argument) and writes crates/emukc_battle/src/simulation/installation_types.rs: every
abyssal ship with an `installtype`, the ships with each of the separate marks the damage
formulas read (`isSupplyDepot`, `isAnchorage`, `isDock`, `isSummerBB`, `isSummerCA`), and the
last abyssal id the source knows. It prints the counts and sums that the test
`the_installation_tables_follow_the_source` asserts.

    python3 scripts/gen_installation_types.py [kcSHIPDATA.js]
"""

import re
import subprocess
import sys
import urllib.request
from pathlib import Path

COMMIT = "69097abc"
URL = f"https://raw.githubusercontent.com/KC3Kai/kancolle-replay/{COMMIT}/js/kcSHIPDATA.js"
OUT = Path(__file__).resolve().parent.parent / "crates/emukc_battle/src/simulation/installation_types.rs"
# Abyssal ship ids start here; the source's entries from 3001 are its own (Vita) and not the game's.
ABYSSAL = range(1501, 3001)
MARKS = {
    "isSupplyDepot": ("SUPPLY_DEPOT_IDS", "take the supply depot's multiplier after the cap"),
    "isAnchorage": ("ANCHORAGE_IDS", "take the anchorage's multipliers"),
    "isDock": ("DOCK_IDS", "take the dock's multipliers"),
    "isSummerBB": ("SUMMER_BATTLESHIP_IDS", "take the summer battleship's multipliers"),
    "isSummerCA": ("SUMMER_CRUISER_IDS", "take the summer heavy cruiser's multipliers"),
}


def parse(text: str) -> tuple[dict[int, int], dict[str, list[int]], int]:
    types, marks, ship, last = {}, {mark: [] for mark in MARKS}, None, 0
    for line in text.splitlines():
        if entry := re.match(r"\t(\d+): \{", line):
            ship = int(entry[1])
            if ship in ABYSSAL:
                last = max(last, ship)
        elif ship in ABYSSAL:
            if kind := re.match(r"\t\tinstalltype: (\d+),", line):
                types[ship] = int(kind[1])
            elif mark := re.match(r"\t\t(\w+): true,", line):
                if mark[1] in marks:
                    marks[mark[1]].append(ship)
    return types, {mark: sorted(ids) for mark, ids in marks.items()}, last


def main() -> None:
    if len(sys.argv) > 1:
        text = Path(sys.argv[1]).read_text(encoding="utf-8")
    else:
        with urllib.request.urlopen(URL) as response:
            text = response.read().decode("utf-8")
    types, marks, last = parse(text)
    rows = "".join(f"    ({ship}, {kind}),\n" for ship, kind in sorted(types.items()))
    lists = "".join(
        f"/// The ships that {doc} (`{mark}`).\n"
        f"pub(crate) const {name}: &[i64] = &[\n" + "".join(f"    {ship},\n" for ship in marks[mark]) + "];\n\n"
        for mark, (name, doc) in MARKS.items()
    )
    OUT.write_text(
        "//! Generated by `scripts/gen_installation_types.py` from `kcSHIPDATA.js` of\n"
        f"//! `KC3Kai/kancolle-replay` at `{COMMIT}`. Regenerate it; do not edit it by hand.\n\n"
        "/// The abyssal land targets with the source's `installtype`, sorted by id: 1 soft-skinned,\n"
        "/// 2 pillbox, 3 supply depot, 4 isolated island, 5 northern, 6 harbour summer princess.\n"
        f"pub(crate) const INSTALLATION_TYPES: &[(i64, u8)] = &[\n{rows}];\n\n"
        f"{lists}"
        "/// The last abyssal ship the source knows. A newer one is not in these tables.\n"
        f"pub(crate) const LAST_SOURCE_ABYSSAL_ID: i64 = {last};\n",
        encoding="utf-8",
    )
    subprocess.run(["rustfmt", "--edition", "2024", str(OUT)], check=True)
    for kind in range(1, 7):
        ships = [ship for ship, value in types.items() if value == kind]
        print(f"installtype {kind}: {len(ships)} ships, ids sum {sum(ships)}")
    for mark, ids in marks.items():
        print(f"{mark}: {len(ids)} ships, ids sum {sum(ids)}")
    print(f"last abyssal id: {last}")


if __name__ == "__main__":
    main()
